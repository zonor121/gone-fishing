"""Generate PostgreSQL schema/seed from the maintained SQLite catalog."""
import re
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import sea
import world

root = Path(__file__).resolve().parents[1]
schema = (root / 'db/schema.sql').read_text(encoding='utf-8')
schema = re.sub(r'--[^\n]*', '', schema).replace('PRAGMA foreign_keys=ON;', '')
schema = schema.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
schema = schema.replace("COLLATE NOCASE", '').replace("(datetime('now'))", "(to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS'))")
schema = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', schema)
schema = re.sub(r'\buser\b', 'fishing_user', schema)
schema = schema.replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ')
schema += '\nCREATE UNIQUE INDEX IF NOT EXISTS fishing_username_ci ON fishing_user(lower(username));\n'
seed = (root / 'db/seed.sql').read_text(encoding='utf-8')
seed = re.sub(r'--[^\n]*', '', seed).replace('INSERT OR IGNORE', 'INSERT')
seed = seed.replace(';', ' ON CONFLICT DO NOTHING;')
seed += "\nINSERT INTO location VALUES (4,'sea','Морская рыбалка','#7daec9','#e8eee9','#367e9e','#123e60',0,0) ON CONFLICT DO NOTHING;\n"
seed += "INSERT INTO bait VALUES (5,'shrimp','Креветка',80) ON CONFLICT DO NOTHING;\n"

def literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    return str(value)

fish = [(7,'Скумбрия',.4,2.,2.5,.45,'#79abb5',240,None,None,'dart'), (8,'Треска',1.,7.,1.6,.72,'#a29b76',420,None,None,'heavy'), (9,'Морской окунь',.5,3.5,2.,.58,'#d18369',320,None,None,'dart'), (10,'Тунец',3.,15.,.65,.95,'#537e9a',700,'day',None,'dart')]
for table, rows in [('fish',fish), ('fish_location', [(i,4) for i in range(7,11)]), ('fish_bait',[(7,5,1),(7,4,.7),(8,5,.8),(9,5,1),(9,4,.6),(10,4,.4),(10,5,.25)])]:
    for row in rows:
        seed += 'INSERT INTO ' + table + ' VALUES (' + ','.join(map(literal,row)) + ') ON CONFLICT DO NOTHING;\n'
tables = re.findall(r'CREATE TABLE IF NOT EXISTS (\w+)', schema)
security = '\n'.join(f'ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON {t} FROM anon, authenticated;\nGRANT ALL ON {t} TO service_role;' for t in tables)
security += '\nGRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;\n'
api = (root / 'db/supabase_api.sql').read_text(encoding='utf-8').replace('"user"', 'fishing_user').replace('BEGIN;\n', '', 1).replace('\nCOMMIT;', '')
rod_migration = (root / 'db/migrations/007_linear_rods.sql').read_text(encoding='utf-8')
rod_migration = rod_migration.split('CREATE OR REPLACE FUNCTION', 1)[0].replace('BEGIN;\n', '', 1)
(root / 'db/supabase.sql').write_text('BEGIN;\n' + schema + rod_migration + seed + security + api + '\nCOMMIT;\n', encoding='utf-8')
print('Generated db/supabase.sql')
